import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const bin=process.env.GS_BROWSER_BIN||'agent-browser';
const base=process.argv[2]||'http://127.0.0.1:8766/index.html';
const out=fs.mkdtempSync(path.join(os.tmpdir(),'gs-daily-edges-'));
const run=(...args)=>execFileSync(bin,['--session','gs-daily-edges',...args],{encoding:'utf8',timeout:60000,maxBuffer:1024*1024});
const evaluate=code=>run('eval',`(async()=>{const pause=ms=>new Promise(r=>setTimeout(r,ms));const click=s=>{const el=document.querySelector(s);if(!el)throw Error('Missing '+s);el.click()};const assert=(v,m)=>{if(!v)throw Error(m)};${code}})()`);
const mockDate=key=>evaluate(`const Native=window.__realDate||Date;window.__realDate=Native;window.Date=class extends Native{constructor(...a){super(...(a.length?a:['${key}T12:00:00']))}};`);
const finish=(start=0)=>evaluate(`for(let i=${start};i<3;i++){if(document.querySelector('[data-gd-action="answer"]:not([disabled])'))click('[data-gd-action="answer"][data-gd-index="0"]');await pause(250);click('[data-gd-action="next"]')}assert(!!document.querySelector('.gs-gold-daily-result'),'No result');`);
console.log('Evidence: '+out);
run('set','viewport','390','844');
run('set','media','dark','reduced-motion');
run('open',base+'?goldDaily=today');
evaluate(`localStorage.removeItem(GameSharpGoldDailyLoop.key);localStorage.removeItem(GameSharpMainDaily.key);localStorage.setItem('gs_sound_on','0');`);
mockDate('2026-09-12');
evaluate(`GameSharpGoldDaily.openDaily();click('[data-gd-action="daily-start"]');click('[data-gd-action="answer"][data-gd-index="1"]');`);
run('open',base+'?goldDaily=today');
mockDate('2026-09-12');
evaluate(`GameSharpGoldDaily.openDaily();assert(document.querySelector('[data-gd-action="daily-start"]').textContent.includes('Resume'),'No resume');click('[data-gd-action="daily-start"]');assert(document.querySelectorAll('[data-gd-action="answer"][disabled]').length===4,'Lost first answer');click('[data-gd-action="next"]');`);
finish(1);
evaluate(`window.firstResult=JSON.stringify(GameSharpGoldDailyLoop.createStore(localStorage).get('2026-09-12'));window.firstMain=localStorage.getItem(GameSharpMainDaily.key);window.firstCount=localStorage.getItem('gamesharp_challenges_done');click('[data-gd-action="list"]');click('[data-gd-action="daily-start"]');`);
finish();
evaluate(`assert(JSON.stringify(GameSharpGoldDailyLoop.createStore(localStorage).get('2026-09-12'))===firstResult,'Replay overwrote first result');assert(localStorage.getItem(GameSharpMainDaily.key)===firstMain,'Replay overwrote main history');assert(localStorage.getItem('gamesharp_challenges_done')===firstCount,'Replay awarded duplicate credit');click('[data-gd-action="list"]');`);
console.log('Refresh/resume and immutable replay PASS');
mockDate('2026-09-13');
evaluate(`click('[data-gd-action="daily-start"]');assert(!document.querySelector('[data-gd-action="answer"]'),'Started an unseen new-day title');assert(document.querySelector('h1').textContent.includes('Serve'),'Did not show new day');click('[data-gd-action="daily-start"]');`);
mockDate('2026-09-14');
finish();
evaluate(`const s=GameSharpGoldDailyLoop.createStore(localStorage);assert(s.get('2026-09-13')?.complete,'Midnight moved the completion');assert(!s.get('2026-09-14'),'Credited wrong date');click('[data-gd-action="list"]');assert(document.querySelector('h1').textContent.includes('Miss'),'Home did not advance');`);
console.log('Stale tab and mid-lesson midnight PASS');
// Open the catalogue first so the Daily store has not yet touched storage.
run('open',base+'?goldDaily=1');
evaluate(`const get=Storage.prototype.getItem;Storage.prototype.getItem=function(k){if(k==='gs_gold_daily_loop_v1')throw Error('blocked');return get.call(this,k)};GameSharpGoldDaily.openDaily();assert(document.querySelector('.gs-gold-daily-calendar').textContent.includes('Saving is unavailable'),'Silent storage failure');click('[data-gd-action="daily-start"]');`);
finish();
console.log('Storage unavailable still playable with explicit warning PASS');
run('screenshot',path.join(out,'storage-result.png'));
run('set','viewport','1280','844');
run('open',base+'?goldDaily=today');
evaluate(`GameSharpGoldDaily.openDaily();assert(document.querySelector('.gs-gold-daily').scrollWidth<=innerWidth,'Desktop overflow');`);
run('screenshot',path.join(out,'desktop-home.png'));
evaluate(`click('[data-gd-action="daily-start"]');click('[data-gd-action="expand-evidence"]');`);
run('screenshot',path.join(out,'desktop-focus.png'));
evaluate(`click('[data-gd-action="close-focus"]');`);
finish();
run('screenshot',path.join(out,'desktop-result.png'));
console.log('Desktop full lesson and Focus PASS');
run('open',base+'?goldDaily=1');
evaluate(`assert(document.querySelectorAll('[data-gd-action="start"]').length===21,'Catalogue regression');`);
run('open',base);
evaluate(`assert(window.GameSharpMainDaily,'Main Daily assets missing');assert(!document.querySelector('.gs-daily-pilot-entry'),'Competing pilot entry');assert(document.querySelector('.gs-daily-card-hit').getAttribute('onclick')==='startDailyChallenge()','Main Daily entry missing');click('.gs-daily-card-hit');assert(document.querySelector('[data-gd-action="daily-start"]'),'Home did not open new Daily');`);
console.log('Catalogue remains separate; promoted Home entry PASS');
console.log(JSON.stringify({out,status:'PASS'}));
run('close');
